@router.get("/")
def list_domains(auth: dict = Depends(require_auth)):
    """List all domains for the authenticated publisher."""
    with get_db() as db:
        rows = db.execute(
            "SELECT * FROM domains WHERE publisher_id = ? ORDER BY created_at DESC",
            (auth["sub"],)
        ).fetchall()
    return [dict(r) for r in rows]


@router.post("/", response_model=DomainResponse)
def add_domain(body: AddDomainRequest, auth: dict = Depends(require_auth)):
    """
    Add a new domain to CrawlBouncer.

    integration_mode="reverse_proxy" (default): returns the CNAME
    target the publisher must configure at their DNS registrar. CrawlBouncer
    sees and gates every request itself once DNS is verified.

    integration_mode="bolt_on": no DNS change — the publisher keeps
    whatever CDN/DNS they already have. Returns an edge API key
    (shown exactly once) for their own server to call POST /v1/decide
    per-request. Both modes reuse the same bot detection and rules; they
    differ only in who enforces them.
    """
    domain = body.domain.lower().strip()

    if not DOMAIN_RE.match(domain):
        raise HTTPException(400, f"'{domain}' is not a valid domain name")

    if body.integration_mode == "reverse_proxy":
        if not body.origin_url or not body.origin_url.startswith(("http://", "https://")):
            raise HTTPException(400, "origin_url must start with http:// or https:// for reverse-proxy domains")
        _validate_public_origin(body.origin_url)
    # bolt_on domains don't need an origin_url at all — CrawlBouncer never
    # proxies to it, the publisher's own server already is the origin.
    # An optional one is still accepted (for display only) but not
    # validated or SSRF-checked, since CrawlBouncer never fetches it.

    with get_db() as db:
        # Check not already registered
        existing = db.execute(
            "SELECT id FROM domains WHERE domain = ?", (domain,)
        ).fetchone()
        if existing:
            raise HTTPException(409, f"{domain} is already registered with CrawlBouncer")

        domain_id = str(uuid.uuid4()).replace("-", "")[:16]

        if body.integration_mode == "bolt_on":
            raw_edge_key = f"cb_edge_{secrets.token_urlsafe(32)}"
            edge_key_hash = hashlib.sha256(raw_edge_key.encode()).hexdigest()
            # dns_verified/ssl_active are hardcoded True in the response below
            # (nothing to verify, no DNS change, publisher's own origin already
            # has TLS) — they must be persisted the same way, or every refresh
            # after creation reads the columns' real default (0) and the
            # dashboard shows "Pending" on a domain with nothing to verify.
            db.execute("""
                INSERT INTO domains (id, publisher_id, domain, origin_url, integration_mode, edge_api_key_hash, dns_verified, ssl_active, active)
                VALUES (?,?,?,?,'bolt_on',?,1,1,1)
            """, (domain_id, auth["sub"], domain, body.origin_url, edge_key_hash))
        else:
            cname_target = _make_cname_target(domain_id)
            db.execute("""
                INSERT INTO domains (id, publisher_id, domain, origin_url, cname_target, integration_mode)
                VALUES (?,?,?,?,?,'reverse_proxy')
            """, (domain_id, auth["sub"], domain, body.origin_url, cname_target))

    audit(auth["sub"], auth["sub"], "domain.created", "domain", domain_id,
          {"domain": domain, "integration_mode": body.integration_mode})

    if body.integration_mode == "bolt_on":
        return DomainResponse(
            id=domain_id,
            domain=domain,
            origin_url=body.origin_url,
            integration_mode="bolt_on",
            dns_verified=True,   # nothing to verify — there's no DNS change
            ssl_active=True,     # the publisher's own origin already has TLS
            active=True,
            edge_api_key=raw_edge_key,
            edge_integration_instructions={
                "decide_endpoint": "/v1/decide",
                "header":          "X-Edge-Key",
                "note":            (
                    "This key is shown once — store it now. Your own server calls "
                    "POST /v1/decide with this header on every request before serving "
                    "content, and enforces whatever it returns (allow/block). "
                    "See /api/docs for the full contract and integrations/bolt-on/ in the "
                    "repo for copyable Nginx and Node.js snippets."
                ),
            },
        )

    return DomainResponse(
        id=domain_id,
        domain=domain,
        origin_url=body.origin_url,
        integration_mode="reverse_proxy",
        cname_target=cname_target,
        dns_verified=False,
        ssl_active=False,
        active=False,
        dns_instructions={
            "record_type":  "CNAME",
            "name":         "@  (or your domain root)",
            "value":        cname_target,
            "ttl":          300,
            "note":         "DNS propagation typically takes 5–30 minutes.",
            "verify_url":   f"/api/domains/{domain_id}/verify",
        },
    )


@router.get("/{domain_id}/verify")
def verify_dns(domain_id: str, auth: dict = Depends(require_auth)):
    """
    Check if the domain's DNS is pointing to CrawlBouncer.
    Call this every 30 seconds after updating DNS until it returns verified=true.
    """
    with get_db() as db:
        domain_row = db.execute(
            "SELECT * FROM domains WHERE id = ? AND publisher_id = ?",
            (domain_id, auth["sub"])
        ).fetchone()

    if not domain_row:
        raise HTTPException(404, "Domain not found")

    domain       = domain_row["domain"]
    cname_target = domain_row["cname_target"]
    verified     = _verify_dns(domain, cname_target)

    if verified and not domain_row["dns_verified"]:
        with get_db() as db:
            db.execute(
                "UPDATE domains SET dns_verified=1, active=1 WHERE id=?",
                (domain_id,)
            )
        audit(auth["sub"], auth["sub"], "domain.dns_verified", "domain", domain_id, {"domain": domain})

    return {
        "domain":        domain,
        "cname_target":  cname_target,
        "dns_verified":  verified,
        "message": (
            "DNS verified. Your site is now protected by CrawlBouncer."
            if verified else
            "DNS not yet detected. Make sure you added the CNAME record and wait 5–30 minutes."
        ),
    }


@router.get("/{domain_id}/nginx-config")
def get_nginx_config(domain_id: str, auth: dict = Depends(require_auth)):
    """Return the auto-generated nginx config for a verified domain."""
    with get_db() as db:
        row = db.execute(
            "SELECT * FROM domains WHERE id=? AND publisher_id=?",
            (domain_id, auth["sub"])
        ).fetchone()

    if not row:
        raise HTTPException(404, "Domain not found")

    if not row["dns_verified"]:
        raise HTTPException(400, "DNS not yet verified. Verify DNS first.")

    config = _generate_nginx_config(row["domain"], row["origin_url"], domain_id)
    return {"domain": row["domain"], "nginx_config": config}


@router.post("/{domain_id}/rotate-key")
def rotate_edge_key(domain_id: str, auth: dict = Depends(require_auth)):
    """Issue a new edge key for a bolt-on domain, invalidating the old
    one immediately. For a key that's been lost or possibly leaked —
    there was previously no way to do this short of deleting and
    re-adding the domain, which would also have reset any per-path
    rules attached to it."""
    with get_db() as db:
        row = db.execute(
            "SELECT id, integration_mode FROM domains WHERE id=? AND publisher_id=?",
            (domain_id, auth["sub"])
        ).fetchone()
        if not row:
            raise HTTPException(404, "Domain not found")
        if row["integration_mode"] != "bolt_on":
            raise HTTPException(400, "Only bolt-on domains have an edge key to rotate")

        raw_edge_key = f"cb_edge_{secrets.token_urlsafe(32)}"
        edge_key_hash = hashlib.sha256(raw_edge_key.encode()).hexdigest()
        # Scoped to id AND publisher_id again, not just id — the row was
        # already confirmed to belong to this publisher above, but a
        # second check here means a TOCTOU race with a concurrent
        # ownership change (e.g. domain transfer, if that's ever added)
        # can't let this UPDATE apply to a domain that changed hands
        # between the SELECT and this statement.
        db.execute(
            "UPDATE domains SET edge_api_key_hash=? WHERE id=? AND publisher_id=?",
            (edge_key_hash, domain_id, auth["sub"])
        )

    audit(auth["sub"], auth["sub"], "domain.edge_key_rotated", "domain", domain_id)

    return {
        "domain_id": domain_id,
        "edge_api_key": raw_edge_key,
        "note": "This key is shown once — store it now. The previous key stopped working immediately.",
    }


@router.delete("/{domain_id}")
def remove_domain(domain_id: str, auth: dict = Depends(require_auth)):
    """Remove a domain from CrawlBouncer.

    Deletes every row across the tables that reference this domain_id
    (foreign_keys=ON is enforced — see database.py — so leaving any of
    these out doesn't just orphan data, it makes the DELETE itself
    raise sqlite3.IntegrityError and 500 the whole request the moment
    the domain has ever had a path rule, a mirror override, a single
    logged request or a WAF event against it — i.e. any domain that has ever served real
    traffic). Only `crawler_rules` was previously cleaned up here;
    everything else in this list was found by cross-referencing every
    `domain_id ... REFERENCES domains(id)` column in database.py, not
    guessed at.

    Removing a domain erases its request/WAF history along with its
    configuration.
    """
    with get_db() as db:
        row = db.execute(
            "SELECT id FROM domains WHERE id=? AND publisher_id=?",
            (domain_id, auth["sub"])
        ).fetchone()
        if not row:
            raise HTTPException(404, "Domain not found")
        for table in (
            "crawler_rules", "path_rules", "mirror_settings", "mirror_cache",
            "requests", "waf_events",
        ):
            db.execute(f"DELETE FROM {table} WHERE domain_id=?", (domain_id,))
        db.execute("DELETE FROM domains WHERE id=?", (domain_id,))
    audit(auth["sub"], auth["sub"], "domain.deleted", "domain", domain_id)

    return {"message": "Domain removed successfully"}


@router.get("/{domain_id}/robots.txt")
def robots_txt(domain_id: str):
    """
    Auto-generate robots.txt from the publisher's crawler rules.
    Served at /robots.txt on every publisher domain via nginx.
    """
    with get_db() as db:
        rules = db.execute(
            "SELECT crawler_name, action FROM crawler_rules WHERE domain_id=?",
            (domain_id,)
        ).fetchall()

    from app.middleware.bot_detection import CRAWLERS

    rule_map = {r["crawler_name"]: r["action"] for r in rules}
    lines = ["User-agent: *", "Allow: /", ""]

    for name, info in CRAWLERS.items():
        # robots_only tokens (Google-Extended, Applebot-Extended) are honoured
        # *only* via robots.txt, so this file is the one place they can be blocked.
        action = rule_map.get(name, info["default_action"])
        lines.append(f"User-agent: {name}")
        lines.append("Disallow: /" if action == "block" else "Allow: /")
        lines.append("")

    from fastapi.responses import PlainTextResponse
    return PlainTextResponse("\n".join(lines), media_type="text/plain")
