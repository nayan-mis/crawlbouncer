"""
CrawlBouncer — Domains API
Publishers add their domains, get DNS instructions, verify DNS,
and get auto-HTTPS. Each verified domain gets an nginx config generated.
"""
from __future__ import annotations
import re
import uuid
import subprocess
import ipaddress
import socket
import secrets
import hashlib
from urllib.parse import urlparse
from fastapi import APIRouter, HTTPException, Depends, Header
from pydantic import BaseModel, Field
from typing import Optional

from app.config import cfg
from app.database import get_db
from app.api.auth import require_auth
from app.services.audit import record as audit

router = APIRouter(prefix="/api/domains", tags=["domains"])

PROXY_BASE = cfg.PROXY_BASE               # set PROXY_BASE in .env to your gateway hostname
DOMAIN_RE  = re.compile(r"^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$")


# ─────────────────────────────────────────────────────────────────
# SCHEMAS
# ─────────────────────────────────────────────────────────────────

class AddDomainRequest(BaseModel):
    domain: str
    origin_url: Optional[str] = None
    integration_mode: str = Field("reverse_proxy", pattern="^(reverse_proxy|bolt_on)$")


class DomainResponse(BaseModel):
    id: str
    domain: str
    origin_url: Optional[str] = None
    integration_mode: str = "reverse_proxy"
    cname_target: Optional[str] = None
    dns_verified: bool
    ssl_active: bool
    active: bool
    dns_instructions: Optional[dict] = None
    edge_api_key: Optional[str] = None
    edge_integration_instructions: Optional[dict] = None


# ─────────────────────────────────────────────────────────────────
# HELPERS
# ─────────────────────────────────────────────────────────────────

def _make_cname_target(domain_id: str) -> str:
    """Each domain gets a unique CNAME target on our proxy."""
    short = domain_id[:8]
    return f"{short}.{PROXY_BASE}"


def _verify_dns(domain: str, expected_cname: str) -> bool:
    """
    Check if domain's CNAME record points to our proxy.
    Uses system `dig` command. Falls back to socket on failure.
    """
    try:
        result = subprocess.run(
            ["dig", "+short", "CNAME", domain],
            capture_output=True, text=True, timeout=5
        )
        output = result.stdout.strip().rstrip(".")
        if output == expected_cname:
            return True
    except Exception:
        pass

    # Fallback: try to resolve
    try:
        import socket
        resolved = socket.getfqdn(domain)
        if PROXY_BASE in resolved:
            return True
    except Exception:
        pass

    return False


def _validate_public_origin(origin_url: str) -> None:
    """Reject origins that would turn CrawlBouncer into an internal-network proxy."""
    parsed = urlparse(origin_url)
    if parsed.scheme not in {"http", "https"} or not parsed.hostname:
        raise HTTPException(400, "origin_url must be an absolute HTTP(S) URL")
    if parsed.username or parsed.password:
        raise HTTPException(400, "origin_url must not contain credentials")
    try:
        addresses = {item[4][0] for item in socket.getaddrinfo(parsed.hostname, parsed.port or 443)}
    except socket.gaierror:
        # Origins are commonly configured before their DNS record is live.
        # The gateway must resolve and re-check before every upstream connect.
        return
    for address in addresses:
        if not ipaddress.ip_address(address).is_global:
            raise HTTPException(400, "origin_url must resolve only to globally routable addresses")


def _generate_nginx_config(domain: str, origin_url: str, domain_id: str) -> str:
    """Generate nginx server block for a verified customer domain."""
    return f"""# CrawlBouncer — Auto-generated config for {domain}
# Generated by CrawlBouncer platform
server {{
    listen 80;
    listen [::]:80;
    server_name {domain};
    return 301 https://$host$request_uri;
}}

server {{
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name {domain};

    ssl_certificate     /etc/letsencrypt/live/{domain}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/{domain}/privkey.pem;
    ssl_protocols       TLSv1.2 TLSv1.3;
    ssl_ciphers         ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256;

    # Security headers
    add_header X-Frame-Options          DENY;
    add_header X-Content-Type-Options   nosniff;
    add_header X-XSS-Protection        "1; mode=block";
    add_header Strict-Transport-Security "max-age=31536000" always;

    # Access log in JSON format
    access_log /var/log/nginx/cb_{domain_id}.log cb_json;

    location / {{
        proxy_pass          http://cb_app;
        proxy_http_version  1.1;
        proxy_set_header    Host              $host;
        proxy_set_header    X-Real-IP         $remote_addr;
        proxy_set_header    X-Forwarded-For   $proxy_add_x_forwarded_for;
        proxy_set_header    X-Forwarded-Proto $scheme;
        proxy_read_timeout  30s;
        proxy_connect_timeout 5s;
    }}

    # robots.txt served by CrawlBouncer
    location = /robots.txt {{
        proxy_pass http://cb_app/robots/{domain_id};
    }}
}}
"""


